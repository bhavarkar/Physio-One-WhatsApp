"""Pydantic schemas and typed models for LLM gateway.

Single Organization Edition: Physio One Clinic.
Standardizes requests, responses, streaming chunks, tool calls, and usage metrics across all providers.
"""
from enum import Enum
from typing import Optional, List, Dict, Any, Union
import json
from pydantic import BaseModel, Field, model_validator


class MessageRole(str, Enum):
    """Normalized chat message roles."""
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class ToolCall(BaseModel):
    """Normalized tool call requested by LLM."""
    id: str = Field(description="Unique call ID generated by LLM")
    name: str = Field(description="Function / tool name to execute")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Parsed arguments dictionary")

    @classmethod
    def from_raw(cls, call_id: str, name: str, raw_args: Union[str, Dict[str, Any]]) -> "ToolCall":
        """Safe constructor parsing arguments JSON if string."""
        if isinstance(raw_args, dict):
            return cls(id=call_id, name=name, arguments=raw_args)
        try:
            parsed = json.loads(raw_args) if raw_args else {}
            if not isinstance(parsed, dict):
                parsed = {"raw": parsed}
            return cls(id=call_id, name=name, arguments=parsed)
        except Exception:
            return cls(id=call_id, name=name, arguments={"raw": raw_args})


class ToolDefinition(BaseModel):
    """Specification of an executable tool exposed to LLM."""
    name: str
    description: str
    parameters: Dict[str, Any] = Field(
        default_factory=lambda: {"type": "object", "properties": {}},
        description="JSON Schema describing input arguments",
    )


class ChatMessage(BaseModel):
    """Normalized conversation message representation."""
    role: MessageRole
    content: Optional[str] = None
    name: Optional[str] = None
    tool_call_id: Optional[str] = None
    tool_calls: Optional[List[ToolCall]] = None

    @model_validator(mode="after")
    def validate_content_or_tool_calls(self):
        if self.role == MessageRole.ASSISTANT:
            if not self.content and not self.tool_calls:
                # Assistant must have content or tool calls
                self.content = ""
        elif self.role == MessageRole.TOOL:
            if self.tool_call_id is None:
                raise ValueError("Tool messages must provide tool_call_id.")
        return self


class LLMOptions(BaseModel):
    """Execution parameters for LLM request."""
    temperature: float = Field(default=0.2, ge=0.0, le=2.0)
    max_tokens: int = Field(default=1000, ge=1, le=128000)
    timeout_seconds: float = Field(default=30.0, ge=1.0, le=180.0)
    response_format: Optional[Dict[str, Any]] = None  # e.g. {"type": "json_object"}
    stop_sequences: Optional[List[str]] = None


class LLMUsage(BaseModel):
    """Token usage and cost accounting."""
    input_tokens: int = 0
    output_tokens: int = 0
    total_tokens: int = 0
    estimated_cost: Optional[float] = None

    @model_validator(mode="after")
    def compute_total(self):
        if self.total_tokens == 0 and (self.input_tokens > 0 or self.output_tokens > 0):
            self.total_tokens = self.input_tokens + self.output_tokens
        return self


class LLMResponse(BaseModel):
    """Unified response returned by provider adapters."""
    content: Optional[str] = None
    tool_calls: List[ToolCall] = Field(default_factory=list)
    usage: LLMUsage = Field(default_factory=LLMUsage)
    model: str
    provider: str
    finish_reason: Optional[str] = None
    latency_ms: int = 0
    raw_response: Optional[Dict[str, Any]] = None


class LLMStreamChunk(BaseModel):
    """Incremental chunk produced by streaming LLM calls."""
    delta_content: Optional[str] = None
    delta_tool_calls: Optional[List[ToolCall]] = None
    finish_reason: Optional[str] = None
    usage: Optional[LLMUsage] = None


class ProviderCapabilities(BaseModel):
    """Capabilities explicitly exposed by a provider adapter."""
    supports_tools: bool = False
    supports_structured_output: bool = False
    supports_streaming: bool = False
    supports_vision: bool = False


class ProviderValidationResult(BaseModel):
    """Diagnostic outcome of provider health / configuration test."""
    is_valid: bool
    status: str = "healthy"  # healthy, degraded, unhealthy
    latency_ms: int = 0
    error_message: Optional[str] = None
    capabilities: ProviderCapabilities
    detected_models: List[str] = Field(default_factory=list)
    details: Optional[Dict[str, Any]] = None
